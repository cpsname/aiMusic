import '../cli/project.dart';
import '../config/script.dart';

String timeCode(double s, int fps) {
  final whole = s.truncate();
  final frames = ((s - whole) * fps).round();
  String two(int v) => v.toString().padLeft(2, '0');
  return '${two(whole ~/ 3600)}:${two(whole ~/ 60 % 60)}:${two(whole % 60)}:${two(frames)}';
}

/// `dist/<app>/upload-checklist.md`: what to upload where, in which order,
/// with which poster frame, next to the localization's name and subtitle.
String uploadChecklist(Project project, {required Map<String, Map<String, String>> texts}) {
  final app = project.app;
  final fps = project.encoding.fps;
  final scripts = project.orderedAll;
  final slots = [for (final d in app.devices) app.slots[d]!];
  String scene(PreviewScript s, double t) => s.segmentAt(t).id;
  final out = StringBuffer()
    ..writeln('# App Store preview upload checklist — ${app.brand.name}')
    ..writeln()
    ..writeln('Generated by `store-preview checklist --app ${app.id}` from `store_preview/${app.id}/`; edit those')
    ..writeln('files, not this one. Rules: docs/store/apple-preview-rules.md (packages/store_preview).')
    ..writeln()
    ..writeln('Files: `dist/${app.id}/<localization>/<script>.mp4`, with `<script>.poster.png`,')
    ..writeln('`<script>.captions.srt` (every text on screen) and `<script>.edl.json` (what is footage,')
    ..writeln('what is not, every licensed item).')
    ..writeln()
    ..writeln('## Before uploading')
    ..writeln()
    ..writeln('1. `store-preview validate --app ${app.id}` passes all three layers (spec, compliance, narrative).')
    ..writeln('2. Watch each preview muted: the intro card and the first caption state the claim on their own.')
    ..writeln('3. The app version under review ships everything the previews show.');
  if (app.requiresPurchase) {
    out.writeln('4. The end card discloses the purchase: "${texts[app.storefronts.first.id]?[app.brand.disclosureKey!] ?? ''}" '
        '(${app.storefronts.first.id}; localized in each).');
  }
  out
    ..writeln()
    ..writeln('## Every localization')
    ..writeln();
  for (final slot in slots) {
    out.writeln('**${slot.ascDisplay}** — upload in this order (the first autoplays):');
    for (final (i, s) in scripts.indexed) {
      out.writeln('${i + 1}. `${s.id}${slot.fileSuffix}.mp4` — ${s.title} (${s.duration.toStringAsFixed(0)} s)');
    }
    out.writeln();
  }
  final shared = app.publish.sharedPosterAt;
  out.writeln('**Poster frame.** App Store Connect uses 0:05 unless told otherwise.');
  if (shared != null) {
    out.writeln('Upload tools that set one still frame for every preview (fastlane deliver\'s '
        '`preview_frame_time_code`) use `${timeCode(shared, fps)}`: it lies on the finished product in every preview '
        '(${[for (final s in scripts) '${s.id}: ${scene(s, shared)}'].join(', ')}). Uploading by hand, set each preview\'s own:');
  } else {
    out.writeln('After each upload, open the preview\'s poster frame setting, move to its time code and save:');
  }
  out
    ..writeln()
    ..writeln('| Preview | Poster frame | On that frame |')
    ..writeln('| --- | --- | --- |');
  for (final s in scripts) {
    out.writeln('| ${s.id} | ${timeCode(s.posterAt, fps)} | scene `${scene(s, s.posterAt)}` |');
  }
  out
    ..writeln()
    ..writeln('## Per storefront')
    ..writeln()
    ..writeln('| Localization | Name | Subtitle | Upload | Done |')
    ..writeln('| --- | --- | --- | --- | --- |');
  final order = scripts.map((s) => '`${s.id}`').join(' → ');
  for (final st in app.storefronts) {
    out.writeln('| `${st.id}` | ${st.asoName} | ${st.asoSubtitle} | $order | ☐ |');
    // A served localization shows the storefront's previews (template
    // ADR-0017); its name and subtitle are its own listing's.
    for (final l in st.serves) {
      out.writeln('| `$l` | — | — | $order (`${st.id}`\'s) | ☐ |');
    }
  }
  return out.toString();
}
