import 'dart:convert';
import 'dart:io';

import 'package:crypto/crypto.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:path/path.dart' as p;
import 'package:store_preview/store_preview.dart';

void main() {
  late String source;
  late String target;
  void write(String root, String path, String value) => (File(p.join(root, path))..parent.createSync(recursive: true)).writeAsStringSync(value);

  Future<Map<String, Object?>> installLegacyStamp() async {
    final stamp = await vendor(from: source, to: target);
    const generated = 'packages/store_preview_driver/.flutter-plugins-dependencies';
    write(target, generated, '{"generated":true}\n');
    final files = [...vendoredFiles(target), generated]..sort();
    final bytes = <int>[];
    for (final file in files) {
      bytes
        ..addAll(utf8.encode('$file\n'))
        ..addAll(File(p.join(target, file)).readAsBytesSync());
    }
    final legacy = {...stamp, 'sha256': sha256.convert(bytes).toString(), 'files': files.length};
    write(target, 'packages/store_preview/$vendorStampName', jsonEncode(legacy));
    return legacy;
  }

  setUp(() {
    source = Directory.systemTemp.createTempSync('vendor_source_').path;
    target = Directory.systemTemp.createTempSync('vendor_target_').path;
    for (final path in vendoredPaths) {
      write(source, path.startsWith('packages/') ? '$path/pubspec.yaml' : path, 'template fixture\n');
    }
    write(target, 'lib/main.dart', 'business logic\n');
    addTearDown(() => Directory(source).deleteSync(recursive: true));
    addTearDown(() => Directory(target).deleteSync(recursive: true));
  });

  test('same and nested repositories are refused without deleting the source', () async {
    final digest = vendorDigest(source);
    await expectLater(vendor(from: source, to: source), throwsA(isA<ConfigError>()));
    final child = Directory(p.join(source, 'child'))..createSync();
    await expectLater(vendor(from: source, to: child.path), throwsA(isA<ConfigError>()));
    expect(vendorDigest(source), digest);
  });

  test('missing source and symlink inputs cannot replace an existing installation', () async {
    await vendor(from: source, to: target);
    final installed = vendorDigest(target);
    final path = vendoredPaths.last;
    File(p.join(source, path)).deleteSync();
    await expectLater(vendor(from: source, to: target), throwsA(isA<ConfigError>()));
    expect(vendorDigest(target), installed);
    Link(p.join(source, path)).createSync(p.join(target, path));
    await expectLater(vendor(from: source, to: target), throwsA(isA<ConfigError>()));
    expect(vendorDigest(target), installed);
  });

  test('repeat vendor is deterministic and preserves app-specific files', () async {
    final first = await vendor(from: source, to: target);
    final second = await vendor(from: source, to: target);
    expect(second, first);
    expect(vendorDrift(target), isNull);
    expect(File(p.join(target, 'lib/main.dart')).readAsStringSync(), 'business logic\n');
    expect(Directory(target).listSync().where((f) => p.basename(f.path).startsWith('.store-preview-vendor-')), isEmpty);
  });

  test('local tool drift fails rather than discarding an unbackported fix', () async {
    await vendor(from: source, to: target);
    write(target, 'packages/store_preview/local_fix.dart', 'local change\n');
    final before = vendorDigest(target);
    await expectLater(vendor(from: source, to: target), throwsA(isA<ConfigError>()));
    expect(vendorDigest(target), before);
  });

  test('generated Flutter plugin metadata is excluded and clean checkouts retain their digest', () async {
    const generated = ['packages/store_preview_driver/.flutter-plugins', 'packages/store_preview_driver/.flutter-plugins-dependencies'];
    final digest = vendorDigest(source);
    for (final file in generated) {
      write(source, file, 'local generated paths\n');
    }
    expect(vendorDigest(source), digest);
    final stamp = await vendor(from: source, to: target);
    expect(stamp['sha256'], digest);
    expect(stamp['files'], vendoredFiles(target).length);
    for (final file in generated) {
      expect(vendoredFiles(source), isNot(contains(file)));
      expect(File(p.join(target, file)).existsSync(), isFalse);
      write(target, file, 'regenerated by Flutter\n');
    }
    expect(vendorDrift(target), isNull);
    for (final file in generated) {
      File(p.join(target, file)).deleteSync();
    }
    expect(vendorDrift(target), isNull);
    expect(await vendor(from: source, to: target), stamp);
  });

  test('an exact legacy stamp migrates without carrying generated metadata', () async {
    final legacy = await installLegacyStamp();
    expect(vendorDigest(target), isNot(legacy['sha256']));
    expect(vendorDrift(target), isNull);
    final upgraded = await vendor(from: source, to: target);
    expect(upgraded['sha256'], vendorDigest(source));
    expect(upgraded['files'], (legacy['files'] as int) - 1);
    expect(File(p.join(target, 'packages/store_preview_driver/.flutter-plugins-dependencies')).existsSync(), isFalse);
    expect(vendorDrift(target), isNull);
  });

  test('legacy migration still refuses source drift without overwriting it', () async {
    await installLegacyStamp();
    const file = 'packages/store_preview/pubspec.yaml';
    write(target, file, 'local source edit\n');
    expect(vendorDrift(target), contains('differs from its stamp'));
    await expectLater(vendor(from: source, to: target), throwsA(isA<ConfigError>()));
    expect(File(p.join(target, file)).readAsStringSync(), 'local source edit\n');
  });

  test('a late installation failure restores earlier replaced directories', () async {
    write(target, 'packages/store_preview/pubspec.yaml', 'previous\n');
    write(target, 'scripts', 'a file blocks the script directory\n');
    await expectLater(vendor(from: source, to: target), throwsA(isA<FileSystemException>()));
    expect(File(p.join(target, 'packages/store_preview/pubspec.yaml')).readAsStringSync(), 'previous\n');
    expect(Directory(p.join(target, 'packages/store_preview_driver')).existsSync(), isFalse);
    expect(File(p.join(target, 'lib/main.dart')).readAsStringSync(), 'business logic\n');
  });
}
