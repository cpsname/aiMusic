/// The create home's single list (contract 02 v2.1 `Inspiration`), as the
/// product repo seeds it (`internal/songlet/infra/inspirationcfg/
/// inspirations.yaml`, 32 entries: the 16 templates and the 16 v2 scenes in
/// one list, order = `sort`). The preview and cover URLs are the product
/// repo's own, served as given (never rebased onto the mock host). Regenerate
/// this table from that YAML when it changes.
class InspirationSeed {
  const InspirationSeed(
    this.slug,
    this.nameEn,
    this.nameZh,
    this.styleEn,
    this.styleZh,
    this.previewAudioUrl,
    this.durationSec,
    this.coverImageUrl,
    this.occasion,
    this.requiresRecipient,
    this.defaultModel,
    this.hintEn,
    this.hintZh, {
    this.genre,
    this.vocals,
    this.inputRequired = false,
  });

  final String slug;
  final String nameEn;
  final String nameZh;
  final String styleEn;
  final String styleZh;
  final String previewAudioUrl;
  final int durationSec;
  final String coverImageUrl;
  final String occasion;
  final bool requiresRecipient;
  final String defaultModel;
  final String hintEn;
  final String hintZh;
  final String? genre;
  final String? vocals;
  final bool inputRequired;

  /// Stable per slug (UUID v5 shape over a mock namespace; the platform
  /// derives its own — clients only rely on stability).
  String get id {
    final h = sha1.convert(utf8.encode('songlet-mock-inspiration:$slug')).bytes;
    final b = [...h.take(16)];
    b[6] = (b[6] & 0x0f) | 0x50;
    b[8] = (b[8] & 0x3f) | 0x80;
    final hex = b.map((x) => x.toRadixString(16).padLeft(2, '0')).join();
    return '${hex.substring(0, 8)}-${hex.substring(8, 12)}-${hex.substring(12, 16)}-${hex.substring(16, 20)}-${hex.substring(20)}';
  }

  /// The `Inspiration` JSON at position [sort].
  Map<String, Object?> toJson(int sort) => {
    'id': id,
    'slug': slug,
    'name': {'en': nameEn, 'zh': nameZh},
    'style': {'en': styleEn, 'zh': styleZh},
    'preview_audio_url': previewAudioUrl,
    'duration_sec': durationSec,
    'cover_image_url': coverImageUrl,
    'sort': sort,
    'occasion': occasion,
    'requires_recipient': requiresRecipient,
    if (genre != null) 'suggested_genre': genre,
    if (vocals != null) 'default_vocals': vocals,
    'default_model': defaultModel,
    'composer': {
      'hint': {'en': hintEn, 'zh': hintZh},
      'input_required': inputRequired,
    },
  };
}

